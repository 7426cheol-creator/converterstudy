class RCDischarge(HybridSystem):
    state_names = ("v_C",)
    state_units = ("V",)

    def __init__(self, C: float, R: float, shares: list[float]):
        self.C, self.R, self.shares = C, R, shares
        self._m = AffineMode(f"ex10rc|{C:.12g}|{R:.12g}", np.array([[-1.0 / (R * C)]]), np.zeros(1), label="DIS")

    def mode(self, q):
        return self._m

    def outputs(self, q):
        out = {"v": np.array([1.0, 0.0]), "i": np.array([1.0 / self.R, 0.0])}
        for k, s in enumerate(self.shares):
            out[f"v{k}"] = np.array([s, 0.0])
        return out

    def stored_energy(self):
        return np.diag([self.C, 0.0])

    def powers(self, q):
        out = {"p_R": np.array([[1.0 / self.R, 0.0], [0.0, 0.0]])}
        for k, s in enumerate(self.shares):
            out[f"p{k}"] = np.array([[s / self.R, 0.0], [0.0, 0.0]])
        return out

    def describe(self, q):
        return "DIS"


def discharge_circuit(v: dict, R: float) -> Circuit:
    n = int(v["N_ser"])
    c = Circuit("ex10_dis", 600, 300, title=f"능동 방전: 스위치 + 직렬 저항 {n}개")
    c.add("capacitor", "C", 110, 150, 90, "C_dc", f"{v['C'] * 1e3:g} mF · {v['V0']:g} V", lpos=(88, 146, "end"))
    q = c.add("nmos", "Q", 300, 60, 0, "방전 스위치", lpos=(300, 30, "middle"))
    c.wire("w_top", (110, 120), (110, 60), q["a"])
    shown = min(n, 4)
    ys = np.linspace(95, 215, shown)
    prev = (460, 60)
    c.wire("w_q", q["b"], prev)
    for k, y in enumerate(ys):
        r = c.add("resistor", f"R{k}", 460, float(y), 90, f"R{k + 1}" if shown == n or k < shown - 1 else f"R{k + 1}…R{n}", f"{R / n:.4g} Ω" if k == 0 else "", lpos=(482, float(y) + 4, "start"))
        c.wire(f"w_r{k}", prev, r["a"])
        prev = r["b"]
    c.wire("w_ret", prev, (460, 260), (110, 260), (110, 180))
    c.probe("pI", "i", 390, 48, "right", "i")
    c.mode("DIS", "방전 중", ["C", "Q", "w_top", "w_q", "w_ret"] + [f"R{k}" for k in range(shown)] + [f"w_r{k}" for k in range(shown)], "스위치를 켜면 C가 직렬 저항으로 방전: 초기 전력이 최대, 에너지는 저항 비율로 나뉜다")
    return c


def run_discharge(v: dict) -> Result:
    res = Result("EX10", "discharge_resistor", "A (폐형식) + C (정확 RC 엔진) + 독립 ODE")
    C, V0, Ve, treq = v["C"], v["V0"], v["V_end"], v["t_req"]
    tolR, tolC = v["tol_R"] / 100.0, v["tol_C"] / 100.0
    n = int(v["N_ser"])
    lnr = math.log(V0 / Ve)
    R_nom = treq / (C * lnr)
    R_wc = treq / (C * (1 + tolC) * lnr) / (1 + tolR)
    R = R_nom if v["basis"] == "nominal" else R_wc
    tb = abs(C - 1e-3) < 1e-15 and abs(V0 - 800) < 1e-9 and abs(Ve - 60) < 1e-9 and abs(treq - 2) < 1e-12
    # worst sharing: one resistor at +tol, the rest at -tol
    share_w = (1 + tolR) / ((1 + tolR) + (n - 1) * (1 - tolR)) if n > 1 else 1.0
    shares = [share_w] + [(1 - share_w) / (n - 1)] * (n - 1) if n > 1 else [1.0]
    sysm = RCDischarge(C, R, shares)
    t_end = 1.6 * treq * (1 + tolR) * (1 + tolC)
    tr = simulate(sysm, "DIS", [V0], 0.0, t_end)
    t60 = _seg_root_level(tr, "v", Ve, 0.0, t_end)
    E_rem = 0.5 * C * (V0 * V0 - Ve * Ve)
    P0 = V0 * V0 / R
    res.add_metric("R_nom", "공칭 설계 R = t/(C·ln(V₀/V_f))", R_nom, "Ω", ref=772.121 if tb else ref.rc_discharge(C, V0, Ve, treq)["R"], ref_label="교재 772.121 Ω" if tb else "폐형식 (reference)", tol=1e-6, basis="이상 RC, 공차 없음")
    res.add_metric("R_used", "사용한 R (설계 기준: " + ("공칭" if v["basis"] == "nominal" else "공차 worst-case") + ")", R, "Ω", basis=f"직렬 {n}개, 각 {R / n:.4g} Ω")
    res.add_metric("P0", "초기 전력 V₀²/R", P0, "W", ref=828.885 if (tb and v["basis"] == "nominal") else None, ref_label="교재 828.885 W", tol=1e-6, basis="t = 0 순간 (전체)")
    res.add_metric("E_rem", "제거 에너지 ½C(V₀² − V_f²)", E_rem, "J", ref=318.2 if tb else None, ref_label="교재 318.2 J", tol=1e-9)
    res.add_metric("t60", f"{Ve:g} V 도달 시각 (정확 엔진)", t60, "s", ref=treq if v["basis"] == "nominal" else None, ref_label="요구 (교육용 가정)", tol=1e-9, basis="공칭 R·C")
    corners = []
    for fr in (1 - tolR, 1 + tolR):
        for fc in (1 - tolC, 1 + tolC):
            corners.append((fr, fc, R * fr * C * fc * lnr))
    t_slow = max(c_[2] for c_ in corners)
    t_fast = min(c_[2] for c_ in corners)
    res.add_metric("t_slow", "가장 느린 공차 corner (R·C 최대)", t_slow, "s", basis=f"R +{tolR * 100:g} %, C +{tolC * 100:g} %", note="요구보다 길면 불만족" if t_slow > treq else "")
    res.add_metric("t_fast", "가장 빠른 corner", t_fast, "s", basis="초기 전력은 이 corner에서 최대")
    P0_fast = V0 * V0 / (R * (1 - tolR))
    res.add_metric("P0_max", "초기 전력 최대 (R −공차)", P0_fast, "W")
    res.add_metric("share", "worst 저항의 전압·에너지 몫", share_w, "", basis=f"1개 +{tolR * 100:g} %, 나머지 −{tolR * 100:g} %")
    R_tot_w = R / n * ((1 + tolR) + (n - 1) * (1 - tolR)) if n > 1 else R * (1 - tolR)
    Vk = V0 * share_w
    Ek = E_rem * share_w
    P0k = V0 * V0 / R_tot_w * share_w
    res.add_metric("Vk", "worst 저항 인가 전압", Vk, "V", note=f"허용 {v['V_res']:g} V (ASSUMED)")
    res.add_metric("Ek", "worst 저항 펄스 에너지", Ek, "J", note=f"허용 {v['E_pulse']:g} J @ 수 s 펄스 (ASSUMED)")
    res.add_metric("P0k", "worst 저항 초기 전력", P0k, "W", note=f"연속 정격 {v['P_cont']:g} W의 {P0k / v['P_cont']:.0f}배 — 펄스 정격으로 본다")
    P_avg = Ek / v["t_rep"]
    res.add_metric("Pavg", "반복 방전 평균 전력 (worst 저항)", P_avg, "W", basis=f"{v['t_rep']:g} s마다 1회 (ASSUMED)")
    P_bleed = V0 * V0 / R

STAGE_KO = {"wait": "대기 (blanking·임계 도달 전)", "filt": "필터·검출", "prop": "전파·로직", "off": "소거 (soft-off/turn-off)", "sys": "MCU·시스템 반응"}


def timeline(v: dict, f: float, t_blank: float | None = None) -> dict:
    """Clearing times of the DESAT and over-current paths for stage-time factor f (A-level algebra).

    Fault current model: i(t) = min(V_dc t / L_f, I_sat) (linear rise, synthetic device-limited
    plateau), then a linear fall over the winning path's turn-off time.
    """
    Vdc, Lf, Isat, Ioc = v["Vdc"], v["Lf"], v["Isat"], v["Ioc"]
    tb = (v["t_blank"] if t_blank is None else t_blank) * f if v["ftype"] == "type1" else 0.0
    t_desat = Isat * Lf / Vdc
    a0 = max(tb, t_desat)
    a_det = a0 + v["t_filt"] * f
    a_cmd = a_det + v["t_prop"] * f
    a_clr = a_cmd + v["t_soft"] * f
    stagesA = [("wait", 0.0, a0), ("filt", a0, a_det), ("prop", a_det, a_cmd), ("off", a_cmd, a_clr)]
    if Ioc < Isat:
        t_oc = Ioc * Lf / Vdc
        b_det = t_oc + (v["t_sense"] + v["t_cmp"]) * f
        b_cmd = b_det + v["t_iso"] * f
        b_clr = b_cmd + v["t_off"] * f
        stagesB = [("wait", 0.0, t_oc), ("filt", t_oc, b_det), ("prop", b_det, b_cmd), ("off", b_cmd, b_clr)]
    else:
        b_det = b_cmd = b_clr = math.inf
        stagesB = []
    # the first path to command the turn-off owns it (a driver in its fault sequence ignores later commands)
    if a_cmd <= b_cmd:
        win, t_cmd, t_fall, t_clr, t_det = "DESAT", a_cmd, v["t_soft"] * f, a_clr, a_det
    else:
        win, t_cmd, t_fall, t_clr, t_det = "과전류", b_cmd, v["t_off"] * f, b_clr, b_det
    s0 = min(a_det, b_det)
    stagesS = [("prop", s0, s0 + v["t_report"] * f), ("sys", s0 + v["t_report"] * f, s0 + (v["t_report"] + v["t_mcu"]) * f)]
    I_off = min(Vdc * t_cmd / Lf, Isat)
    dV = v["Lsig"] * I_off / t_fall
    # device energy: v_DS = 0 while saturated (i < I_sat), V_dc on the plateau, V_dc + dV during the fall
    E_plateau = Vdc * Isat * max(t_cmd - t_desat, 0.0) if t_cmd > t_desat else 0.0
    E_off = (Vdc + dV) * I_off * t_fall / 2.0
    return {"f": f, "t_blank": tb, "t_desat": t_desat, "A": (a_det, a_cmd, a_clr), "B": (b_det, b_cmd, b_clr), "win": win, "t_cmd": t_cmd, "t_fall": t_fall, "t_clr": t_clr, "t_det": t_det,
            "stagesA": stagesA, "stagesB": stagesB, "stagesS": stagesS, "I_off": I_off, "dV": dV, "E_plateau": E_plateau, "E_off": E_off, "E_sc": E_plateau + E_off}


def fault_current(v: dict, tl: dict, t: np.ndarray) -> np.ndarray:
    i = np.minimum(v["Vdc"] * t / v["Lf"], v["Isat"])
    fall = (t >= tl["t_cmd"]) & (t < tl["t_cmd"] + tl["t_fall"])
    i = np.where(t >= tl["t_cmd"], 0.0, i)
    i = np.where(fall, tl["I_off"] * (1.0 - (t - tl["t_cmd"]) / tl["t_fall"]), i)
    return i


def device_power(v: dict, tl: dict, t: np.ndarray) -> np.ndarray:
    i = fault_current(v, tl, t)
    vds = np.where((t >= tl["t_desat"]) & (t < tl["t_cmd"]), v["Vdc"], 0.0)
    vds = np.where((t >= tl["t_cmd"]) & (t < tl["t_cmd"] + tl["t_fall"]), v["Vdc"] + tl["dV"], vds)
    return vds * i


def clock_clearing(v: dict, f: float, dt: float = 1e-10) -> float:
    """Independent path: a discrete-event clock stepping the detector state machines tick by tick.

    The first path to reach its turn-off stage owns the gate; the other path is then blocked.
    """
    Vdc, Lf, Isat, Ioc = v["Vdc"], v["Lf"], v["Isat"], v["Ioc"]
    tb = v["t_blank"] * f if v["ftype"] == "type1" else 0.0
    stA, cA = "arm", 0.0
    stB, cB = "arm", 0.0
    t = 0.0
    t_end = 50e-6
    while t < t_end:
        i = min(Vdc * t / Lf, Isat)
        desat = i >= Isat * (1 - 1e-12)
        # DESAT path
        if stA == "arm" and t >= tb - 1e-15 and desat:
            stA, cA = "filt", 0.0
        elif stA == "filt":
            cA += dt
            if cA >= v["t_filt"] * f - 1e-15:
                stA, cA = "prop", 0.0
        elif stA == "prop":
            cA += dt
            if cA >= v["t_prop"] * f - 1e-15:
                stA, cA = "off", 0.0
                if stB != "off":
                    stB = "blocked"
        elif stA == "off":
            cA += dt
            if cA >= v["t_soft"] * f - 1e-15:
                return t
        # over-current path
        if stB == "arm" and i >= Ioc and Ioc < Isat:
            stB, cB = "filt", 0.0
        elif stB == "filt":
            cB += dt
            if cB >= (v["t_sense"] + v["t_cmp"]) * f - 1e-15:
                stB, cB = "prop", 0.0
        elif stB == "prop":
            cB += dt
            if cB >= v["t_iso"] * f - 1e-15:
                stB, cB = "off", 0.0
                if stA != "off":
                    stA = "blocked"
        elif stB == "off":
            cB += dt
            if cB >= v["t_off"] * f - 1e-15:
                return t
        t += dt
    return math.inf


def false_trip_rate(t_blank: np.ndarray, mu: float, sig: float, fsw: float) -> np.ndarray:
    """Synthetic: V_DS settle time after a normal turn-on ~ N(mu, sig); a trip when it exceeds blanking."""
    from scipy.special import erfc

    p = 0.5 * erfc((t_blank - mu) / (sig * math.sqrt(2.0)))
    return p * fsw * 3600.0



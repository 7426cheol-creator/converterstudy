class ASCDQ(HybridSystem):
    """Active short circuit: v_d = v_q = 0 on the dq machine at constant speed; x = [i_d, i_q]."""

    state_names = ("i_d", "i_q")
    state_units = ("A", "A")

    def __init__(self, m: Machine, we: float):
        self.m, self.we = m, we
        A = np.array([[-m.Rs / m.Ld, we * m.Lq / m.Ld], [-we * m.Ld / m.Lq, -m.Rs / m.Lq]])
        b = np.array([0.0, -we * m.psi / m.Lq])
        self._m = AffineMode(f"ex10asc|{m}|{we:.12g}", A, b, label="ASC")

    def mode(self, q):
        return self._m

    def outputs(self, q):
        return {"id": np.array([1.0, 0.0, 0.0]), "iq": np.array([0.0, 1.0, 0.0])}

    def stored_energy(self):
        return np.diag([1.5 * self.m.Ld, 1.5 * self.m.Lq, 0.0])

    def powers(self, q):
        m, we = self.m, self.we
        pem = np.zeros((3, 3))
        pem[1, 2] = pem[2, 1] = 0.5 * 1.5 * we * m.psi
        pem[0, 1] = pem[1, 0] = 0.5 * 1.5 * we * (m.Ld - m.Lq)
        return {"p_cu": np.diag([1.5 * m.Rs, 1.5 * m.Rs, 0.0]), "p_em": pem}

    def describe(self, q):
        return "ASC"


def asc_equilibrium(m: Machine, we: float):
    """The lab's own steady ASC point: x* = -A^{-1} b of the ASC dq model (numerical solve)."""
    s = ASCDQ(m, we)
    md = s.mode("ASC")
    x = np.linalg.solve(md.A, -md.b)
    return float(x[0]), float(x[1])


class Freewheel(HybridSystem):
    """All gates off: the inverter is a three-phase diode bridge on a non-salient machine model.

    x = [i_a, i_b, cos th, sin th] (+ v_dc when the battery is disconnected); i_c = -i_a - i_b;
    back-EMF e_k = -w_e psi sin(th - ph_k) is linear in the oscillator states.  Each phase is 'P'
    (upper diode, terminal at DC+, i_k < 0), 'N' (lower diode, i_k > 0) or 'F' (blocking, i_k = 0).
    Diode turn-off (current zero) and turn-on (terminal voltage reaching a rail) are guards; after
    every event the complementarity rules are re-applied.  L = (L_d + L_q)/2 (angle average).
    """

    EPS_I = 1e-7  # A: turn-off guard offset so a tangential turn-on is not undone by round-off

    def __init__(self, m: Machine, we: float, Vdc: float, battery: bool, Cdc: float, Rb: float):
        self.m, self.we, self.V, self.bat, self.C, self.Rb = m, we, Vdc, battery, Cdc, Rb
        self.L = 0.5 * (m.Ld + m.Lq)
        self.R = m.Rs
        self.n = 4 if battery else 5
        self.state_names = ("i_a", "i_b", "cos θ", "sin θ") + (() if battery else ("v_dc",))
        self._cache: dict = {}
        self._key = f"ex10fw|{m}|{we:.12g}|{Vdc:.12g}|{battery}|{Cdc:.12g}|{Rb:.12g}"
        self.eps_v = 1e-7 * max(Vdc, 1.0)

    # linear rows over the augmented state
    def e_vec(self, k):
        z = np.zeros(self.n + 1)
        cp, sp = math.cos(PHASES[k]), math.sin(PHASES[k])
        z[2] = self.we * self.m.psi * sp
        z[3] = -self.we * self.m.psi * cp
        return z

    def i_vec(self, k):
        z = np.zeros(self.n + 1)
        if k == 0:
            z[0] = 1.0
        elif k == 1:
            z[1] = 1.0
        else:
            z[0] = z[1] = -1.0
        return z

    def v_vec(self):
        z = np.zeros(self.n + 1)
        if self.bat:
            z[-1] = self.V
        else:
            z[4] = 1.0
        return z

    def _u(self, st):
        return self.v_vec() if st == "P" else np.zeros(self.n + 1)

    def mode(self, q):
        md = self._cache.get(q)
        if md is not None:
            return md
        n, L, R = self.n, self.L, self.R
        D = np.zeros((n, n + 1))
        cond = [k for k in range(3) if q[k] != "F"]
        di = {k: np.zeros(n + 1) for k in range(3)}
        if len(cond) == 3:
            vn = sum(self._u(q[k]) for k in range(3)) / 3.0
            for k in range(3):
                di[k] = (self._u(q[k]) - vn - R * self.i_vec(k) - self.e_vec(k)) / L
        elif len(cond) == 2:
            j, k = cond
            dj = ((self._u(q[j]) - self._u(q[k])) - (self.e_vec(j) - self.e_vec(k))) / (2.0 * L) - R / L * self.i_vec(j)
            di[j], di[k] = dj, -dj
        D[0], D[1] = di[0], di[1]
        D[2, 3], D[3, 2] = -self.we, self.we
        if not self.bat:
            idc = sum((-self.i_vec(k) for k in range(3) if q[k] == "P"), np.zeros(n + 1))
            vv = np.zeros(n + 1)
            vv[4] = 1.0
            D[4] = (idc - vv / self.Rb) / self.C
        md = AffineMode(f"{self._key}|{q}", D[:, :n], D[:, n], label="".join(q))
        self._cache[q] = md
        return md

    def _reset(self, new):
        def r(z):
            z = z.copy()
            if new == ("F", "F", "F"):
                z[0] = z[1] = 0.0
            elif new[0] == "F":
                z[0] = 0.0
            elif new[1] == "F":
                z[1] = 0.0
            elif new[2] == "F":
                z[1] = -z[0]
            return z

        return r

    def guards(self, q):
        g = []
        one = np.zeros(self.n + 1)
        one[-1] = 1.0
        cond = [k for k in range(3) if q[k] != "F"]
        for k in cond:
            new = ("F", "F", "F") if len(cond) == 2 else tuple("F" if x == k else q[x] for x in range(3))
            sgn = 1 if q[k] == "P" else -1
            g.append(Guard(f"i_{'abc'[k]} = 0", self.i_vec(k) - sgn * self.EPS_I * one, sgn, (lambda qq, new=new: new), self._reset(new)))
        V = self.v_vec()
        if len(cond) == 2:
            m = [x for x in range(3) if x not in cond][0]
            nu = tuple("P" if x == m else q[x] for x in range(3))
            nd = tuple("N" if x == m else q[x] for x in range(3))
            g.append(Guard(f"v_{'abc'[m]}0 = V_dc", 1.5 * self.e_vec(m) - 0.5 * V - self.eps_v * one, 1, (lambda qq, t=nu: t)))
            g.append(Guard(f"v_{'abc'[m]}0 = 0", 1.5 * self.e_vec(m) + 0.5 * V + self.eps_v * one, -1, (lambda qq, t=nd: t)))
        if not cond:
            for j in range(3):
                for k in range(3):
                    if j != k:
                        t = tuple("P" if x == j else ("N" if x == k else "F") for x in range(3))
                        g.append(Guard(f"e_{'abc'[j]} − e_{'abc'[k]} = V_dc", self.e_vec(j) - self.e_vec(k) - V - self.eps_v * one, 1, (lambda qq, t=t: t)))
        return g

    def after_event(self, q, z):
        if q is None:
            cur = (z[0], z[1], -z[0] - z[1])
            sc = max(max(abs(x) for x in cur), 1e-9)
            q = tuple("N" if x > 1e-12 * sc else ("P" if x < -1e-12 * sc else "F") for x in cur)
        q = list(q)
        for _ in range(6):
            cond = [k for k in range(3) if q[k] != "F"]
            V = float(self.v_vec() @ z)
            E = [float(self.e_vec(k) @ z) for k in range(3)]
            tol = 2e-7 * max(abs(V), 1.0)
            if len(cond) == 1:
                q = ["F", "F", "F"]
                continue
            if not cond:
                best = max((E[j] - E[k] - V, j, k) for j in range(3) for k in range(3) if j != k)
                if best[0] > tol:
                    q = ["F", "F", "F"]
                    q[best[1]], q[best[2]] = "P", "N"
                    continue
                break
            if len(cond) == 2:
                mm = [x for x in range(3) if x not in cond][0]
                vm0 = 0.5 * V + 1.5 * E[mm]
                if vm0 > V + tol:
                    q[mm] = "P"
                    continue
                if vm0 < -tol:
                    q[mm] = "N"
                    continue
            break
        return tuple(q)

    def outputs(self, q):
        out = {"ia": self.i_vec(0), "ib": self.i_vec(1), "ic": self.i_vec(2)}
        out["idc"] = sum((-self.i_vec(k) for k in range(3) if q[k] == "P"), np.zeros(self.n + 1))
        for k in range(3):
            out[f"e{k}"] = self.e_vec(k)
        if not self.bat:
            vv = np.zeros(self.n + 1)
            vv[4] = 1.0
            out["vdc"] = vv
        return out

    def stored_energy(self):
        W = np.zeros((self.n + 1, self.n + 1))
        W[0, 0] = W[1, 1] = 2.0 * self.L
        W[0, 1] = W[1, 0] = self.L
        if not self.bat:
            W[4, 4] = self.C
        return W

    def powers(self, q):
        n1 = self.n + 1

        def sym(a, b):
            return 0.5 * (np.outer(a, b) + np.outer(b, a))

        pem = sum(sym(self.e_vec(k), self.i_vec(k)) for k in range(3))
        pcu = self.R * sum(np.outer(self.i_vec(k), self.i_vec(k)) for k in range(3))
        idc = sum((-self.i_vec(k) for k in range(3) if q[k] == "P"), np.zeros(n1))
        out = {"p_gen": -pem, "p_cu": pcu}
        if self.bat:
            out["p_dc"] = sym(self.v_vec(), idc)
        else:
            vv = np.zeros(n1)
            vv[4] = 1.0
            out["p_dc"] = np.outer(vv, vv) / self.Rb
        return out

    def describe(self, q):
        return "".join(q)



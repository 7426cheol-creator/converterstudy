def _seg_root(tr, name: str, t0: float, t1: float, n: int = 400):
    """First zero crossing of an affine output inside [t0, t1], located on the exact solution."""
    for s, off, h in tr.window(t0, t1):
        c = tr.system.outputs(s.q).get(name)
        if c is None:
            continue
        za = s.z0 if off == 0.0 else propagator(s.mode, off) @ s.z0

        def f(t, c=c, s=s, za=za):
            return float(c @ (propagator(s.mode, t) @ za))

        ts = np.linspace(0.0, h, n + 1)
        prev = f(0.0)
        for a, b in zip(ts[:-1], ts[1:]):
            fb = f(b)
            if prev == 0.0:
                return s.t0 + off + a
            if prev * fb < 0:
                return s.t0 + off + brentq(f, a, b, xtol=1e-18, rtol=1e-15)
            prev = fb
    return None



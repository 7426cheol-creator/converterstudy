class RLCFault(HybridSystem):
    """x = [i, v_C]; i flows out of C+ through L, R and the fault path back to C-.

    q: 'RLC' (capacitor discharges), 'CLAMP' (v_C held at -V_cl by the bridge diodes, the fault
    current freewheels through L, R and the diodes), 'OFF' (current zero, nothing left to move).
    """

    state_names = ("i", "v_C")
    state_units = ("A", "V")

    def __init__(self, L: float, C: float, R: float, clamp: bool, Vcl: float):
        self.L, self.C, self.R, self.clamp, self.Vcl = L, C, R, clamp, Vcl
        self._key = f"ex10rlc|{L:.12g}|{C:.12g}|{R:.12g}|{clamp}|{Vcl:.12g}"

    def mode(self, q):
        L, C, R = self.L, self.C, self.R
        A = np.zeros((2, 2))
        b = np.zeros(2)
        if q == "RLC":
            A[0, 0], A[0, 1] = -R / L, 1.0 / L
            A[1, 0] = -1.0 / C
        elif q == "CLAMP":
            A[0, 0] = -R / L
            b[0] = -self.Vcl / L
        return AffineMode(f"{self._key}|{q}", A, b, label=q)

    def guards(self, q):
        if q == "RLC" and self.clamp:

            def to_clamp(z):
                z = z.copy()
                z[1] = -self.Vcl
                return z

            return [Guard("v_C = −V_cl (브리지 diode 도통)", np.array([0.0, 1.0, self.Vcl]), -1, lambda q: "CLAMP", to_clamp)]
        if q == "CLAMP":

            def to_off(z):
                z = z.copy()
                z[0] = 0.0
                return z

            return [Guard("i = 0 (diode 차단)", np.array([1.0, 0.0, 0.0]), -1, lambda q: "OFF", to_off)]
        return []

    def outputs(self, q):
        e_i = np.array([1.0, 0.0, 0.0])
        vC = np.array([0.0, 1.0, 0.0])
        if q == "RLC":
            vL = np.array([-self.R, 1.0, 0.0])
        elif q == "CLAMP":
            vL = np.array([-self.R, 0.0, -self.Vcl])
        else:
            vL = np.zeros(3)
        return {"i": e_i, "vC": vC, "vL": vL, "vR": self.R * e_i, "iD": e_i if q == "CLAMP" else np.zeros(3), "iC": e_i if q == "RLC" else np.zeros(3)}

    def stored_energy(self):
        return np.diag([self.L, self.C, 0.0])

    def powers(self, q):
        e_i = np.array([1.0, 0.0, 0.0])
        p_D = np.zeros((3, 3))
        if q == "CLAMP":
            p_D[0, 2] = p_D[2, 0] = 0.5 * self.Vcl
        return {"p_R": self.R * np.outer(e_i, e_i), "p_D": p_D}

    def describe(self, q):
        return q


def rlc_peak(V0: float, L: float, C: float, R: float):
    """Peak of the first current half-wave for any damping (the lab's own closed form)."""
    a = R / (2.0 * L)
    w0 = 1.0 / math.sqrt(L * C)
    if a < w0 * (1 - 1e-12):
        wd = math.sqrt(w0 * w0 - a * a)
        t = math.atan(wd / a) / wd
        return t, V0 / (L * wd) * math.exp(-a * t) * math.sin(wd * t)
    if a > w0 * (1 + 1e-12):
        r = math.sqrt(a * a - w0 * w0)
        s1, s2 = -a + r, -a - r
        t = math.log(s2 / s1) / (s1 - s2)
        return t, V0 / (L * (s1 - s2)) * (math.exp(s1 * t) - math.exp(s2 * t))
    t = 1.0 / a
    return t, V0 / L * t * math.exp(-a * t)


def rlc_ivp(V0, L, C, R, clamp, Vcl, t_end, rtol=1e-12):
    """Independent path: hand-written ODE with DOP853, the clamp as a terminal event, E_R as a state."""

    def f(t, y):
        return [(y[1] - R * y[0]) / L, -y[0] / C, R * y[0] ** 2, 0.0]

    def g_clamp(t, y):
        return y[1] + Vcl

    g_clamp.terminal = True
    g_clamp.direction = -1

    def g_peak(t, y):
        return y[1] - R * y[0]

    g_peak.direction = -1
    sol = solve_ivp(f, (0.0, t_end), [0.0, V0, 0.0, 0.0], method="DOP853", rtol=rtol, atol=[1e-9, 1e-9, 1e-12, 1e-12], events=[g_clamp, g_peak] if clamp else [g_peak], dense_output=True)
    pieces = [sol]
    t_pk = float(sol.t_events[-1][0]) if sol.t_events[-1].size else None
    t_cl = float(sol.t_events[0][0]) if clamp and sol.t_events[0].size else None
    if clamp and t_cl is not None and t_cl < t_end:
        y0 = sol.y[:, -1].copy()

        def f2(t, y):
            return [(-Vcl - R * y[0]) / L, 0.0, R * y[0] ** 2, Vcl * y[0]]

        def g_zero(t, y):
            return y[0]

        g_zero.terminal = True
        g_zero.direction = -1
        sol2 = solve_ivp(f2, (t_cl, t_end), [y0[0], -Vcl, y0[2], y0[3]], method="DOP853", rtol=rtol, atol=[1e-9, 1e-9, 1e-12, 1e-12], events=[g_zero], dense_output=True)
        pieces.append(sol2)

    def at(t):
        for p in reversed(pieces):
            if p.t[0] <= t <= p.t[-1]:
                return p.sol(t)
        last = pieces[-1].y[:, -1].copy()
        last[0] = 0.0
        return last

    return at, t_pk, t_cl



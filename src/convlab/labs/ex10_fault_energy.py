def _seg_root_level(tr, name: str, level: float, t0: float, t1: float):
    """First time an affine output crosses ``level`` (exact solution + brentq)."""
    for s, off, h in tr.window(t0, t1):
        c = tr.system.outputs(s.q)[name]
        za = s.z0 if off == 0.0 else propagator(s.mode, off) @ s.z0

        def f(t, c=c, s=s, za=za):
            return float(c @ (propagator(s.mode, t) @ za)) - level

        ts = np.linspace(0.0, h, 201)
        prev = f(0.0)
        for a, b in zip(ts[:-1], ts[1:]):
            fb = f(b)
            if prev * fb <= 0:
                return s.t0 + off + brentq(f, a, b, xtol=1e-15, rtol=1e-15)
            prev = fb
    return None



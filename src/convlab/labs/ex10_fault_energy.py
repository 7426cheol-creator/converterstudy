def rlc_circuit(v: dict) -> Circuit:
    c = Circuit("ex10_rlc", 690, 280, title="DC-link 고장 경로: 수동 RLC (+ 브리지 diode clamp)")
    cc = c.add("capacitor", "C", 120, 150, 90, "C", f"{v['C'] * 1e3:g} mF · {v['V0']:g} V", lpos=(98, 146, "end"))
    dd = c.add("diode", "D", 230, 150, 270, "D (브리지 diode)", f"clamp {'ON' if v['clamp'] == 'diode' else 'OFF'}", lpos=(252, 146, "start"))
    ll = c.add("inductor", "L", 360, 60, 0, "L (busbar)", f"{v['L'] * 1e6:g} µH")
    rr = c.add("resistor", "R", 480, 60, 0, "R", f"{v['R'] * 1e3:g} mΩ")
    sw = c.add("switch", "SW", 560, 150, 90, "단락 (leg)", "t = 0에 닫힘", lpos=(582, 146, "start"))
    c.wire("w_top", cc["a"], (120, 60), (230, 60), dd["b"])
    c.wire("w_top2", (230, 60), ll["a"])
    c.wire("w_lr", ll["b"], rr["a"])
    c.wire("w_rs", rr["b"], (560, 60), sw["a"])
    c.wire("w_bot", sw["b"], (560, 240), (230, 240), dd["a"])
    c.wire("w_bot2", (230, 240), (120, 240), cc["b"])
    c.dot((230, 60), (230, 240))
    c.probe("pI", "i", 420, 48, "right", "i")
    c.text(150, 50, "C+", "node")
    c.text(150, 256, "C−", "node")
    loop = ["L", "R", "SW", "w_top2", "w_lr", "w_rs", "w_bot"]
    c.mode("RLC", "C 방전 (RLC)", ["C", "w_top", "w_bot2"] + loop, "커패시터가 L·R·단락 경로로 방전: 전류가 오르고 에너지가 L과 R로 옮겨 간다", dim=["D"])
    c.mode("CLAMP", "diode clamp", ["D"] + loop, "C 전압이 음으로 가려 하면 브리지 diode가 도통해 C를 우회: L의 남은 에너지가 R과 diode에서 소모", dim=["C"])
    c.mode("OFF", "전류 0", [], "L의 에너지가 모두 소모되어 전류가 멈춤", dim=["C", "D", "L", "R", "SW"])
    return c


def run_rlc(v: dict) -> Result:
    res = Result("EX10", "rlc_fault", "A (폐형식) + C (정확 스위칭 엔진) + 독립 ODE")
    V0, L, C, R = v["V0"], v["L"], v["C"], v["R"]
    clamp = v["clamp"] == "diode"
    Vcl = v["Vcl"]
    t_end = v["t_end"]
    sysm = RLCFault(L, C, R, clamp, Vcl)
    tr = simulate(sysm, "RLC", [0.0, V0], 0.0, t_end)
    E0 = 0.5 * C * V0 * V0
    a = R / (2 * L)
    w0 = 1 / math.sqrt(L * C)
    zeta = a / w0
    under = zeta < 1
    t_pk = _seg_root(tr, "vL", 0.0, t_end)
    i_pk = float(tr.state_at(t_pk)[0][0]) if t_pk is not None else float("nan")
    lo, hi = tr.extrema(0.0, t_end, "i")
    tb = abs(V0 - 800) < 1e-9 and abs(L - 10e-6) < 1e-15 and abs(C - 1e-3) < 1e-15 and abs(R - 0.1) < 1e-12
    res.add_metric("E0", "초기 저장에너지 ½CV₀²", E0, "J", ref=320.0 if tb else None, ref_label="교재 320 J", tol=1e-12, basis="DC-link 커패시터")
    res.add_metric("alpha", "감쇠 α = R/(2L) [s⁻¹]", a, "", ref=5000.0 if tb else None, ref_label="5000 s⁻¹", tol=1e-12)
    if under:
        wd = math.sqrt(w0 * w0 - a * a)
        res.add_metric("wd", "감쇠 고유각주파수 ω_d", wd, "rad/s", ref=8660.25 if tb else None, ref_label="8660.25 rad/s", tol=1e-6)
    res.add_metric("zeta", "감쇠비 ζ = α/ω₀", zeta, "", basis="< 1 이면 진동 (전압 역전)")
    res.add_metric("t_pk", "peak 시각 (엔진: di/dt = 0 근)", t_pk, "s", ref=120.919958e-6 if tb else ref.rlc_underdamped(V0, L, C, R)["t_pk"] if under else None, ref_label="지침 120.919958 µs" if tb else "atan(ω_d/α)/ω_d", tol=1e-8)
    res.add_metric("i_pk", "고장 전류 peak", i_pk, "A", ref=4370.344 if tb else (ref.rlc_underdamped(V0, L, C, R)["i_pk"] if under else None), ref_label="지침 4370.344 A" if tb else "폐형식", tol=1e-7, basis="반도체 전류제한·fuse 없음")
    i10 = float(tr.state_at(min(10e-6, t_end))[0][0])
    i100 = float(tr.state_at(min(100e-6, t_end))[0][0])
    res.add_metric("i10", "i(10 µs)", i10, "A", ref=760.0 if tb else None, ref_label="교재 약 760 A", tol=1e-3)
    res.add_metric("i100", "i(100 µs)", i100, "A", ref=4268.0 if tb else None, ref_label="교재 4268 A", tol=2e-4)
    vlo, _ = tr.extrema(0.0, t_end, "vC")
    res.add_metric("vC_min", "커패시터 전압 최저 (역전)", vlo, "V", basis="음수 = 극성 역전" + (" (diode clamp)" if clamp else ""))
    i2t = tr.integral_output_squared(0.0, t_end, "i")
    res.add_metric("i2t", "i²t = ∫i² dt (창 전체)", i2t, "A²s", basis="fuse 협조에 쓰는 양 — fuse 동작은 모델에 없음")
    E_R = tr.energy(0.0, t_end, "p_R")
    E_D = tr.energy(0.0, t_end, "p_D")
    zT, qT = tr.state_at(t_end)
    W_T = 0.5 * float(zT @ sysm.stored_energy() @ zT)
    res.add_metric("E_R", "R에서 소모된 에너지", E_R, "J", basis=f"0 → {t_end * 1e6:g} µs")
    if clamp:
        t_cl = next((s.t1 for s in tr.segments if s.reason.startswith("guard:v_C")), None)
        res.add_metric("E_D", "diode 경로에서 소모된 에너지 V_cl·∫i dt", E_D, "J")
        if t_cl is not None:
            zc, _ = tr.state_at(t_cl)
            res.add_metric("t_clamp", "diode clamp 시작 시각", t_cl, "s")
            res.add_metric("W_L_clamp", "clamp 순간 L에 남은 에너지", 0.5 * L * zc[0] ** 2, "J", basis="이 에너지는 C로 돌아가지 않고 R·diode에서 소모")
    res.add_metric("W_end", "창 끝에 남은 저장에너지 (L + C)", W_T, "J")
    resid = E0 - W_T - E_R - E_D
    res.add_check(Check("에너지 잔차 W₀ − W(t) − E_R − E_D", "PASS" if abs(resid) / E0 < 1e-9 else "FAIL", resid / E0, "rel", 1e-9,
                        path="½Li² + ½Cv² (상태) vs 저항·diode 전력의 정확 적분 (2차 모멘트) — 상태식과 따로 정의한 에너지 항", independent=True,
                        detail=f"W₀ {E0:.6g} J = W(t) {W_T:.6g} + E_R {E_R:.6g} + E_D {E_D:.6g} J (잔차 {resid:.3g} J)"))
    # independent DOP853 path
    at, t_pk2, _ = rlc_ivp(V0, L, C, R, clamp, Vcl, t_end)
    if under and not tb:
        res.add_check(check_close("peak 전류: 폐형식 vs 정확 엔진", i_pk, ref.rlc_underdamped(V0, L, C, R)["i_pk"], 1e-9, "V₀/(Lω_d)e^{−αt}sin ω_d t의 극값 (reference) vs 행렬지수 해의 di/dt = 0 근", True, "A"))
    if t_pk2 is not None and t_pk is not None:
        res.add_check(check_close("peak 시각: DOP853 event vs 정확 엔진", t_pk2, t_pk, 1e-8, "손으로 쓴 ODE + event(di/dt = 0) vs 행렬지수 해", True, "s"))
    probes = [x for x in (10e-6, 100e-6, t_pk, 0.5 * t_end) if x is not None and x <= t_end]
    errs = [abs(float(at(x)[0]) - float(tr.state_at(x)[0][0])) / max(abs(i_pk), 1.0) for x in probes]
    res.add_check(Check("독립 solver: DOP853 전류 (여러 시각)", "PASS" if max(errs) < 1e-8 else "FAIL", max(errs), "rel", 1e-8, path="손으로 쓴 RLC ODE (rtol 1e-12, clamp는 terminal event) vs 정확 엔진", independent=True,
                        detail="시각 " + ", ".join(f"{x * 1e6:.4g} µs" for x in probes) + " 최대 상대오차 (peak 기준)"))
    E_R_ivp = float(at(t_end)[2])
    res.add_check(check_close("E_R: DOP853 적분 상태 vs 정확 2차 모멘트", E_R_ivp, E_R, 1e-7, "ODE에 ∫Ri² 상태를 추가해 적분 vs 행렬지수 2차 모멘트", True, "J", abs_scale=E0))
    # time series (exact samples) and cumulative energies
    ts = np.linspace(0.0, t_end, 401)
    zi = [tr.state_at(t)[0] for t in ts]
    iv = [float(z[0]) for z in zi]
    vc = [float(z[1]) for z in zi]
    wc = [0.5 * C * x * x for x in vc]
    wl = [0.5 * L * x * x for x in iv]
    er = [tr.energy(0.0, t, "p_R") if t > 0 else 0.0 for t in ts]
    ed = [tr.energy(0.0, t, "p_D") if t > 0 else 0.0 for t in ts]
